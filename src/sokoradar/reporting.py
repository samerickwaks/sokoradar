"""Generated documents: the data quality report and the monthly early-warning bulletin."""

from __future__ import annotations

import pandas as pd

from .config import DOCS_DIR, settings


def _md_table(df: pd.DataFrame, floatfmt: str = "{:.2f}") -> str:
    if df.empty:
        return "_none_\n"
    cols = list(df.columns)
    lines = ["| " + " | ".join(map(str, cols)) + " |", "|" + "---|" * len(cols)]
    for _, r in df.iterrows():
        vals = []
        for c in cols:
            v = r[c]
            if isinstance(v, float):
                vals.append("" if pd.isna(v) else floatfmt.format(v))
            elif isinstance(v, pd.Timestamp):
                vals.append(f"{v:%Y-%m}")
            else:
                vals.append(str(v))
        lines.append("| " + " | ".join(vals) + " |")
    return "\n".join(lines) + "\n"


def data_quality_report(q: dict, series: pd.DataFrame, climate: pd.DataFrame, macro: pd.DataFrame,
                        manifest: dict | None) -> str:
    s = series.copy()
    s["first_month"] = s["first_month"].dt.strftime("%Y-%m")
    s["last_month"] = s["last_month"].dt.strftime("%Y-%m")
    tab = s.sort_values(["commodity", "pricetype", "n_obs"], ascending=[True, True, False])[
        ["market", "county", "asal", "commodity", "pricetype", "first_month", "last_month", "n_obs", "coverage"]]
    md = [
        "# SokoRadar data quality report",
        "",
        "_Generated by `python -m sokoradar.pipeline run --stages prepare`. Do not edit by hand._",
        "",
        "## WFP market prices",
        "",
        f"- Raw file: {q['raw_rows']:,} price rows, {q['raw_markets']} markets, {q['raw_commodities']} commodities, "
        f"{q['raw_period']}.",
        f"- In scope (maize, beans, maize flour, goat meat; retail and wholesale; KES): {q['rows_in_scope']:,} rows.",
        f"- Units converted to KES per kg; {q['rows_unit_unparsed']} rows had units that could not be converted.",
        f"- Market names merged: {q['markets_merged']} "
        + (", ".join(f"{d['market']} -> {d['market_canon']}" for d in q["merged_pairs"]) or "none") + ".",
        f"- Outliers dropped (far from the series' rolling median): {q['outliers_dropped']}.",
        f"- Series before the 36-month rule: {q['series_before_filter']}; kept: {q['series_kept']} "
        f"({q['series_short']} too short). Observations kept: {q['observations_kept']:,} across "
        f"{q['markets_kept']} markets, {q['kept_period']}.",
        "- Targets are never gap-filled: a month without a WFP price has no target.",
        "",
        "### Series used for modelling",
        "",
        _md_table(tab, "{:.3f}"),
        "## Climate (CHIRPS rainfall, MODIS NDVI)",
        "",
        f"- County-months: {len(climate):,}; rainfall to {climate.dropna(subset=['rain_1m_pct'])['month'].max():%Y-%m}, "
        f"NDVI to {climate.dropna(subset=['ndvi_pct'])['month'].max():%Y-%m}.",
        "- Source units are pre-2013 districts; each district PCODE starts with its current county code, so districts"
        " are aggregated to the 47 counties weighted by pixel count.",
        "- Rainfall anomaly ratios are capped at 400% of normal (near-zero long-term averages in dry months).",
        "",
        "## Macro",
        "",
        f"- KES/USD: CBK monthly means where available ({(macro['fx_source'] == 'CBK').sum()} months), filled with the"
        f" rate implied by WFP's own KES and USD prices ({(macro['fx_source'] == 'WFP').sum()} months).",
        f"- World Bank Pink Sheet to {macro.dropna(subset=['global_maize_usd'])['month'].max():%Y-%m}.",
        "",
    ]
    if manifest:
        md += ["## Last download", "", f"Run at {manifest['run_at']} (UTC).", ""]
        md += [f"- {k}: {v['status']}" + (f" ({v.get('error', '')})" if v["status"] != "ok" else "")
               for k, v in manifest["sources"].items()]
        md.append("")
    return "\n".join(md)


def bulletin(forecasts: pd.DataFrame, tot: pd.DataFrame, meta: dict) -> str:
    """Monthly early-warning bulletin for NDMA and county coordinators."""
    live = forecasts[forecasts["live"]]
    labels = {k: v["label"] for k, v in settings()["commodities"].items()}
    md = [
        f"# SokoRadar early-warning bulletin — data to {meta['data_end'][:7]}",
        "",
        f"_Generated {meta['generated_at'][:10]}. Forecasts of retail and wholesale staple prices, 1-3 months ahead,"
        " on WFP's ALPS scale. A forecast is not a certainty: ranges are 80% intervals._",
        "",
    ]
    flagged = live[live["phase"].isin(["Alert", "Crisis"])].sort_values(["h", "p_alert"], ascending=[True, False])
    md += ["## Markets expected in Alert or Crisis", ""]
    if flagged.empty:
        md += ["No live market is expected to reach Alert in the next three months.", ""]
    else:
        t = flagged.assign(commodity=flagged["commodity"].map(labels),
                           target=flagged["target_month"].dt.strftime("%b %Y"),
                           range=flagged["price_lo"].round(0).astype(int).astype(str) + "–"
                           + flagged["price_hi"].round(0).astype(int).astype(str),
                           prob=(100 * flagged["p_alert"]).round(0).astype(int).astype(str) + "%")
        md.append(_md_table(t[["county", "market", "commodity", "pricetype", "target", "phase", "range", "prob",
                               "top_driver"]]))
    md += ["## Next-month outlook, all live markets", ""]
    nxt = live[live["h"] == 1].sort_values(["county", "market"])
    t = nxt.assign(commodity=nxt["commodity"].map(labels), now=nxt["price_now"].round(1),
                   forecast=nxt["price_fcst"].round(1), change=nxt["change_pct"].map("{:+.1f}%".format))
    md.append(_md_table(t[["county", "market", "commodity", "pricetype", "now", "forecast", "change", "phase",
                           "freshness"]], "{:.1f}"))
    if tot is not None and len(tot):
        t1 = tot[tot["h"] == 1]
        md += ["## Pastoral terms of trade (kg of maize one goat buys)", "",
               _md_table(t1[["market_key", "tot_month", "tot_now_kg", "target_month", "tot_fcst_kg"]], "{:.1f}"),
               "Goat prices are World Bank RTFP estimates; the outlook applies SokoRadar's maize forecast.", ""]
    md += ["---", "Sources: WFP (CC BY-IGO) via HDX, CHIRPS and MODIS via HDX, Central Bank of Kenya, World Bank."]
    return "\n".join(md)


def write_doc(name: str, text: str) -> None:
    DOCS_DIR.mkdir(parents=True, exist_ok=True)
    (DOCS_DIR / name).write_text(text, encoding="utf-8")
